"""P67: session close-out verdict — shared reference, vendoring, additive guard."""

import re
import shutil
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
PLUGIN = ROOT / "plugins/session"
SOURCE = PLUGIN / "references/close-verdict.md"
SHARED = "references/_shared/close-verdict.md"
PARTICIPANTS = ["session-recap", "session-loose-ends"]
BANNER = re.compile(r"\A<!-- GENERATED by harness-kit from [^\n]*-->\n\n")


def skill_md(name):
    return (PLUGIN / "skills" / name / "SKILL.md").read_text()


def declared(text):
    m = re.search(r"```harness-kit-shared-references\n(.*?)```", text, re.S)
    return m.group(1).split() if m else []


# TS01 — the contract lives in one source file
def test_source_defines_the_verdict_contract():
    text = SOURCE.read_text().replace("**", "")
    for verdict in ("✅ Close this session", "🟡 Main work done", "🔵 Continue"):
        assert verdict in text
    for bucket in ("Done", "Needs a decision", "Not done"):
        assert bucket in text
    for disposition in ("PROJECTS.md", "commit", "GitHub issue", "Linear"):
        assert disposition in text
    assert "this session only" in text.lower()
    assert "handoff" in text.lower()


# TS02 — participants declare + cite; copies match; status stays out
@pytest.mark.parametrize("name", PARTICIPANTS)
def test_participant_declares_cites_and_vendors(name):
    text = skill_md(name)
    assert "close-verdict.md" in declared(text)
    assert SHARED in text
    copy = (PLUGIN / "skills" / name / SHARED).read_text()
    assert BANNER.match(copy), "vendored copy must carry the generated banner"
    assert BANNER.sub("", copy) == SOURCE.read_text()


def test_session_status_is_untouched_by_the_verdict():
    text = skill_md("session-status")
    assert "close-verdict" not in text
    assert "no close-or-continue verdict" in text


# TS03 — additive: existing verdict/close-out text survives verbatim
def test_recap_keeps_its_existing_close_rule():
    text = skill_md("session-recap")
    assert "The close is `🏁 Close — <verdict>.` (Continue or Close), then:" in text
    assert "Recommend **Close** only when the tree is" in text
    assert text.index("### 🏁 Close") < text.index(SHARED)


def test_loose_ends_keeps_its_close_out_table():
    text = skill_md("session-loose-ends")
    anchor = ("An ID that appears in the report and not in the close-out is a dropped\n"
              "   item, not a completed sweep.")
    assert anchor in text
    assert text.index(anchor) < text.index(SHARED)


# TS04 — a skill directory installed on its own resolves every reference
@pytest.mark.parametrize("name", PARTICIPANTS)
def test_standalone_skill_dir_resolves_references(name, tmp_path):
    dest = tmp_path / name
    shutil.copytree(PLUGIN / "skills" / name, dest)
    cited = set(re.findall(r"`(references/[\w./-]+\.md)`", skill_md(name)))
    assert SHARED in cited
    missing = [c for c in cited if not (dest / c).is_file()]
    assert not missing, f"unresolved in standalone install: {missing}"
